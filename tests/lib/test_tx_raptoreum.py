# Osmium uses an 80-byte base block header (Coin.BASIC_HEADER_SIZE).
BASIC_HEADER_SIZE = 80


def test_osmi_auxpow_block_header_parses():
    raw = bfh(OSMI_BLOCK_676060)
    deser = lib_tx_raptoreum.DeserializerAuxPowDash(raw)
    # Must not raise: the AuxPoW proof (incl. the CbTx-v5 parent coinbase)
    # is consumed end-to-end.
    header = deser.read_header(BASIC_HEADER_SIZE)
    # The header is the base 80 bytes plus the variable-length AuxPoW proof.
    assert len(header) > BASIC_HEADER_SIZE
    assert deser.cursor == len(header)
    # What follows the header is the block's transaction section; this block
    # has a single (coinbase) transaction.
    assert raw[deser.cursor] == 1
